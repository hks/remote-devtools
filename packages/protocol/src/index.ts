/**
 * Remote DevTools — WebSocket protocol (v2)
 *
 * The contract between the relay, the UI and all SDKs. Human-readable version: docs/v2/PROTOCOL.md.
 * The Swift / Kotlin / Flutter SDKs depend on that document, not this file; keep the two in sync.
 *
 * Only "erasable" TypeScript is used (no enum / namespace) so that it can run without
 * compilation via Node type stripping.
 */

export const PROTOCOL_VERSION = 2;

export const WS_PATH_UI = '/ws/ui';
export const WS_PATH_DEVICE = '/ws/device';
export const DISCOVERY_PATH = '/discovery';
/** Service type for optional mDNS discovery. */
export const MDNS_SERVICE_TYPE = '_remotedevtools._tcp';

// ─── Envelope ────────────────────────────────────────────────────────────────

export type Envelope<T extends string = string, P = unknown> = {
    v: number;
    type: T;
    /** Unique message id (generated by the sender). */
    id: string;
    /** Send time (epoch ms). */
    ts: number;
    /** If this is a reply to a request, that request's `id`. */
    replyTo?: string;
    /**
     * The related device on the UI ↔ relay leg: the target when going from UI to device, the source when coming from the device.
     * On device connections the relay fills it in; any value sent by the device is ignored.
     */
    deviceId?: string;
    payload: P;
};

/** Builds the union of all possible envelopes from a `{ type: payload }` map. */
export type MessageOf<M> = { [K in keyof M & string]: Envelope<K, M[K]> }[keyof M & string];

// ─── Field DSL ───────────────────────────────────────────────────────────────

export type SelectOption = string | { label: string; value: string | number };

/** Shared field definition for command arguments, flags and form blocks. */
export type Field =
    | { type: 'text'; label?: string; placeholder?: string; multiline?: boolean; default?: string; required?: boolean }
    | { type: 'number'; label?: string; min?: number; max?: number; step?: number; default?: number; required?: boolean }
    | { type: 'boolean'; label?: string; default?: boolean }
    | { type: 'select'; label?: string; options: readonly SelectOption[]; default?: string | number; required?: boolean }
    | { type: 'json'; label?: string; default?: unknown };

/** Key = argument name; order is preserved. */
export type Fields = Record<string, Field>;

